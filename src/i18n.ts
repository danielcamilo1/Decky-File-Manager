function detectLocale(): string {
  try {
    const steam = (window as any).SteamClient;
    // Try a couple of plausible SteamClient accessors; fall back to navigator
    const maybe = steam?.GetCurrentLanguage?.() || steam?.Localization?.GetLanguage?.() || steam?.language || steam?.lang;
    const candidate = (maybe || navigator.language || (navigator.languages && navigator.languages[0]) || "en").toString();
    // Normalize to our supported keys
    if (/^pt(?:[-_]|$)/i.test(candidate)) return "pt-BR";
    if (/^es(?:[-_]|$)/i.test(candidate)) return "es";
    if (/^zh(?:[-_]|$)/i.test(candidate)) return "zh-CN";
    if (/^fr(?:[-_]|$)/i.test(candidate)) return "fr";
    if (/^de(?:[-_]|$)/i.test(candidate)) return "de";
    return "en";
  } catch (e) {
    return "en";
  }
}

const locale = detectLocale();
const dict = translations[locale] || translations[locale.split("-")[0]] || translations["en"];

export function t(key: string): string {
  return dict[key] ?? translations["en"][key] ?? key;
}

export function getLocale(): string {
  return locale;
}

export default { t, getLocale };

export async function loadRemoteTranslations(baseUrl?: string): Promise<void> {
  const tryUrls: string[] = [];
  const normalizedBase = (baseUrl || "").replace(/\/$/, "");

  // First, try bundled locales (packaged with plugin)
  tryUrls.push(`./locales/${locale}.json`);
  tryUrls.push(`./locales/${locale.split("-")[0]}.json`);

  // Then, try configured remote base if provided
  if (normalizedBase) {
    tryUrls.push(`${normalizedBase}/${locale}.json`);
    const short = locale.split("-")[0];
    if (short !== locale) tryUrls.push(`${normalizedBase}/${short}.json`);
  }

  // Default fallback: try a reasonable raw GitHub location for this plugin
  tryUrls.push(`https://raw.githubusercontent.com/Ciphay/Decky-File-Manager/main/locales/${locale}.json`);
  tryUrls.push(`https://raw.githubusercontent.com/Ciphay/Decky-File-Manager/main/locales/${locale.split("-")[0]}.json`);

  // Check cache (localStorage) first
  try {
    const cacheKey = `i18n_cache_${locale}`;
    const raw = localStorage.getItem(cacheKey);
    if (raw) {
      const parsed = JSON.parse(raw);
      const now = Date.now();
      const ttl = parsed.__ts && parsed.__ts > now - 24 * 60 * 60 * 1000; // 24h
      if (ttl && parsed.data && typeof parsed.data === "object") {
        translations[locale] = { ...(translations[locale] || {}), ...(parsed.data as Record<string, string>) };
        Object.keys(translations[locale]).forEach((k) => {
          (dict as any)[k] = (translations[locale] as any)[k];
        });
        // eslint-disable-next-line no-console
        console.info(`i18n: loaded translations for ${locale} from cache`);
        return;
      }
    }
  } catch (e) {
    // ignore cache errors
  }

  for (const url of tryUrls) {
    if (!url) continue;
    try {
      // eslint-disable-next-line no-console
      console.info(`i18n: attempting to fetch translations from ${url}`);
      const res = await fetch(url, { cache: "no-cache" });
      if (!res.ok) continue;
      const data = await res.json();
      if (typeof data !== "object") continue;
      // Merge fetched translations into our translations map
      translations[locale] = { ...(translations[locale] || {}), ...(data as Record<string, string>) };
      // Update dict reference
      // @ts-ignore mutate exported dict
      Object.keys(translations[locale]).forEach((k) => {
        (dict as any)[k] = (translations[locale] as any)[k];
      });
      // Cache result
      try {
        const cacheKey = `i18n_cache_${locale}`;
        localStorage.setItem(cacheKey, JSON.stringify({ __ts: Date.now(), data: translations[locale] }));
      } catch (e) {
        // ignore cache write errors
      }
      // eslint-disable-next-line no-console
      console.info(`i18n: loaded translations for ${locale} from ${url}`);
      return;
    } catch (e) {
      // eslint-disable-next-line no-console
      console.warn(`i18n: failed to fetch ${url}:`, e);
      continue;
    }
  }
  // eslint-disable-next-line no-console
  console.info(`i18n: no remote translations found for ${locale}`);
}

export function clearI18nCache(): void {
  try {
    localStorage.removeItem(`i18n_cache_${locale}`);
  } catch (e) {
    // ignore
  }
}
